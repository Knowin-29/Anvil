#!/usr/bin/env python3
"""Turn eval_results/*/summary.json into the paper's LaTeX tables.

Replaces the placeholder estimates (the `$\\sim$NN.N` cells) with measured numbers and
marks anything still missing as `--`, so a half-finished sweep produces an honest table
rather than a plausible-looking one.

  python eval/backfill_tables.py --results eval_results --out-dir <paper>/tables
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

# column order in the paper's main table
EMBODIED = ["vsibench", "cv_bench", "erqa", "embspatial", "blink",
            "where2place", "refspatial_bench", "robovqa", "openeqa"]
SHORT = {"vsibench": "VSI-B", "cv_bench": "CV-B", "erqa": "ERQA",
         "embspatial": "EmbSp", "blink": "BLINK", "where2place": "W2P",
         "refspatial_bench": "RefSp", "robovqa": "RoboVQA", "openeqa": "OpenEQA"}
# run tag -> human-readable row label, in the order they should appear
ROWS = [("base", "Qwen3.5-9B (zero-shot)"),
        ("sft_9b_lora", "\\quad + GSA-Bench (LoRA)"),
        ("grpo_9b_lora", "\\quad + RL (verifier reward)"),
        ("sft_9b_full", "\\quad + GSA-Bench (full-param)"),
        ("opd_9b", "GSA-Forge-9B (OPD)")]

REPO_ROOT = Path(__file__).resolve().parents[1]


def fmt(v) -> str:
    return "--" if v is None else f"{v:.1f}"


def trusted_score(entry):
    """Return a score only when the registered trust fields pass the protocol."""
    if isinstance(entry, (int, float)):
        return float(entry)
    if isinstance(entry, dict):
        if isinstance(entry.get("score_if_untrusted"), (int, float)):
            return None
        value = entry.get("score")
        if not isinstance(value, (int, float)):
            return None
        truncation = entry.get("truncation_rate")
        parse_failure = entry.get("parse_failure_rate")
        # Structured summaries without either field predate the trust gate. They
        # remain auditable raw results, but cannot enter publication tables.
        if not isinstance(truncation, (int, float)):
            return None
        if not isinstance(parse_failure, (int, float)):
            return None
        if truncation > 15.0 or parse_failure > 25.0:
            return None
        return float(value)
    return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="eval_results")
    ap.add_argument("--out-dir",
                    default=str(REPO_ROOT / "paper" / "tables"))
    a = ap.parse_args()

    data = {}
    for d in sorted(Path(a.results).glob("*")):
        s = d / "summary.json"
        if s.is_file():
            try:
                data[d.name] = json.loads(s.read_text())
            except Exception:
                pass
    if not data:
        print(f"no results under {a.results}/*/summary.json")
        return 1
    print(f"found runs: {', '.join(data)}")

    lines = [
        "% AUTO-GENERATED by eval/backfill_tables.py — do not hand-edit.",
        "% '--' means that cell has not been measured yet.",
        "\\begin{table*}[t]", "\\centering",
        "\\caption{\\textbf{Main results.} Post-training on GSA-Bench, evaluated through "
        "one unified harness. Cells marked -- are not yet measured.}",
        "\\label{tab:main}", "\\vspace{-2mm}",
        "\\setlength{\\tabcolsep}{3.5pt}", "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{@{}l" + "c" * (len(EMBODIED) + 2) + "@{}}", "\\toprule",
        "\\textbf{Model} & " +
        " & ".join(f"\\rotatebox{{60}}{{{SHORT[b]}}}" for b in EMBODIED) +
        " & \\textbf{Avg} & \\textbf{GSA-test} \\\\", "\\midrule",
    ]
    for tag, label in ROWS:
        r = data.get(tag)
        if r is None:
            continue
        vals = [trusted_score(r.get(b)) for b in EMBODIED]
        got = [v for v in vals if isinstance(v, (int, float))]
        avg = sum(got) / len(got) if got else None
        gsa = trusted_score(r.get("gsa_bench_test"))
        lines.append(label + " & " + " & ".join(fmt(v) for v in vals) +
                     f" & {fmt(avg)} & {fmt(gsa)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table*}"]

    out = Path(a.out_dir) / "tab_main.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")

    missing = [(t, b) for t, _ in ROWS if t in data
               for b in EMBODIED + ["gsa_bench_test"]
               if trusted_score(data[t].get(b)) is None]
    if missing:
        print(f"\n{len(missing)} cells still unmeasured, e.g. {missing[:6]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
