"""Contract and verifier helpers for A_action_interface candidates.

The offline probe emits candidate records, not training labels. This module
keeps the promotion rules explicit so geometry generated by heuristics,
teachers, or metadata cannot silently become stable supervision.
"""

from __future__ import annotations

import hashlib
import math
from dataclasses import asdict, dataclass, field
from typing import Any, Dict, List, Sequence

from .taxonomy import ActionType, SourceProvenance, VerifierStatus


ACTION_INTERFACE_SCHEMA_VERSION = "a_action_interface_candidate_v1"

LABEL_STATUS_CANDIDATE = "candidate"
LABEL_STATUS_TEACHER_GENERATED = "teacher_generated"
LABEL_STATUS_HUMAN_VERIFIED = "human_verified"
LABEL_STATUS_STABLE_TRAINING_LABEL = "stable_training_label"

LABEL_STATUSES = {
    LABEL_STATUS_CANDIDATE,
    LABEL_STATUS_TEACHER_GENERATED,
    LABEL_STATUS_HUMAN_VERIFIED,
    LABEL_STATUS_STABLE_TRAINING_LABEL,
}

REVIEW_DECISION_APPROVE = "approve"
REVIEW_DECISION_REJECT = "reject"
REVIEW_DECISION_UNCERTAIN = "uncertain"
REVIEW_DECISION_PENDING = "pending"

REVIEW_DECISIONS = {
    REVIEW_DECISION_APPROVE,
    REVIEW_DECISION_REJECT,
    REVIEW_DECISION_UNCERTAIN,
    REVIEW_DECISION_PENDING,
}

REQUIRED_INTERFACE_FIELDS: Dict[str, Sequence[str]] = {
    ActionType.PICK.value: ("grasp_point_2d", "jaw_axis_2d"),
    ActionType.PUSH.value: ("push_contact_point_2d", "push_direction_2d"),
    ActionType.PLACE.value: ("place_region_2d",),
    ActionType.REORIENT.value: ("grasp_point_2d",),
}

PROMOTION_BLOCKING_RISK_PREFIXES = (
    "no_native_",
    "not_native_",
    "requires_teacher",
    "teacher_or_human_needed",
    "image_inside_",
    "video_context_required",
    "read_only_",
    "outside_contributor_",
)


@dataclass
class CandidateVerification:
    valid_schema: bool = True
    geometry_valid: bool = True
    provenance_valid: bool = True
    promotion_eligible: bool = False
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    promotion_blockers: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {k: v for k, v in asdict(self).items() if v not in (None, [], "")}


def action_interface_schema() -> Dict[str, Any]:
    """Return the v1 candidate schema as JSON-serializable metadata."""
    return {
        "schema_version": ACTION_INTERFACE_SCHEMA_VERSION,
        "pipeline": "A_action_interface",
        "description": "Candidate schema for 2D action geometry interface outputs.",
        "label_status_values": sorted(LABEL_STATUSES),
        "required_by_action_type": {
            action_type: list(fields)
            for action_type, fields in REQUIRED_INTERFACE_FIELDS.items()
        },
        "stable_label_rules": [
            "stable_training_label must stay false for candidate and teacher_generated records",
            "manual review_decision=approve is required before promotion in the contributor v0 full loop",
            "human_verified or stable_training_label status is required before training use",
            "all required geometry fields for the action_type must be present and valid",
            "source_provenance and verifier_status must always be present",
            "blocking risk flags must be resolved before promotion",
        ],
        "geometry_fields": [
            "grasp_point_2d",
            "jaw_axis_2d",
            "push_contact_point_2d",
            "push_direction_2d",
            "place_region_2d",
        ],
        "support_fields": [
            "bbox",
            "point_2d",
            "region_2d",
            "coordinate_frame",
            "image_path",
            "image_ref",
            "video_ref",
            "frame_refs",
        ],
    }


def make_action_interface_label_id(record: Dict[str, Any]) -> str:
    """Create a deterministic label id from image/object/action identity."""
    image_key = record.get("image_path") or record.get("image_ref") or record.get("sample_id", "")
    parts = [
        str(image_key),
        str(record.get("object_id", "")),
        str(record.get("action_type", "")),
        str(record.get("subtype", "")),
    ]
    digest = hashlib.sha1("|".join(parts).encode("utf-8")).hexdigest()[:16]
    return f"aif_{digest}"


def ensure_action_interface_label_id(record: Dict[str, Any]) -> Dict[str, Any]:
    """Return a shallow copy with label_id populated."""
    out = dict(record)
    if not out.get("label_id"):
        out["label_id"] = make_action_interface_label_id(out)
    return out


def verify_action_interface_candidate(record: Dict[str, Any]) -> CandidateVerification:
    """Verify schema/provenance/geometry consistency for one candidate record."""
    result = CandidateVerification()

    schema_version = record.get("schema_version")
    if schema_version != ACTION_INTERFACE_SCHEMA_VERSION:
        result.valid_schema = False
        result.errors.append(f"schema_version must be {ACTION_INTERFACE_SCHEMA_VERSION}")

    action_type = record.get("action_type")
    if action_type not in REQUIRED_INTERFACE_FIELDS:
        result.valid_schema = False
        result.errors.append(f"invalid action_type: {action_type}")

    label_status = record.get("label_status")
    if label_status not in LABEL_STATUSES:
        result.valid_schema = False
        result.errors.append(f"invalid label_status: {label_status}")

    _check_enum_value(record, "source_provenance", {e.value for e in SourceProvenance}, result)
    _check_enum_value(record, "verifier_status", {e.value for e in VerifierStatus}, result)

    stable_training_label = bool(record.get("stable_training_label", False))
    if label_status in {LABEL_STATUS_CANDIDATE, LABEL_STATUS_TEACHER_GENERATED} and stable_training_label:
        result.provenance_valid = False
        result.errors.append("candidate/teacher_generated records cannot be stable_training_label")
    if stable_training_label and label_status not in {
        LABEL_STATUS_HUMAN_VERIFIED,
        LABEL_STATUS_STABLE_TRAINING_LABEL,
    }:
        result.provenance_valid = False
        result.errors.append("stable_training_label requires human_verified or stable_training_label status")

    _check_bbox(record.get("bbox"), result)
    for field_name in ("point_2d", "grasp_point_2d", "push_contact_point_2d"):
        _check_point(record.get(field_name), field_name, result)
    for field_name in ("jaw_axis_2d", "push_direction_2d"):
        _check_vector(record.get(field_name), field_name, result)
        _check_unit_vector(record.get(field_name), field_name, result)
    for field_name in ("region_2d", "place_region_2d"):
        _check_region(record.get(field_name), field_name, result)

    _check_point_inside_bbox(record.get("grasp_point_2d"), record.get("bbox"), "grasp_point_2d", result)
    _check_point_inside_bbox_or_margin(
        record.get("push_contact_point_2d"), record.get("bbox"), "push_contact_point_2d", result
    )
    _check_point_inside_image(record.get("grasp_point_2d"), record, "grasp_point_2d", result)
    _check_point_inside_image(record.get("push_contact_point_2d"), record, "push_contact_point_2d", result)
    _check_region_inside_image(record.get("place_region_2d"), record, "place_region_2d", result)

    required_fields = REQUIRED_INTERFACE_FIELDS.get(action_type, ())
    missing_required = [field_name for field_name in required_fields if record.get(field_name) is None]
    if missing_required:
        result.warnings.append(
            "missing required geometry for stable label: " + ",".join(missing_required)
        )

    risk_flags = list(record.get("risk_flags") or [])
    result.promotion_blockers.extend(_promotion_blockers(risk_flags))
    if missing_required:
        result.promotion_blockers.extend(f"missing_{field_name}" for field_name in missing_required)
    if label_status in {LABEL_STATUS_CANDIDATE, LABEL_STATUS_TEACHER_GENERATED}:
        result.promotion_blockers.append(f"label_status_{label_status}")
    if record.get("verifier_status") != VerifierStatus.AUTO_VERIFIABLE.value:
        result.promotion_blockers.append("not_auto_verifiable")

    result.geometry_valid = not any(
        error.startswith(("invalid bbox", "invalid point", "invalid vector", "invalid region"))
        or "outside bbox" in error
        or "outside image" in error
        or "not unit length" in error
        for error in result.errors
    )
    result.provenance_valid = result.provenance_valid and not any(
        "source_provenance" in error or "verifier_status" in error
        for error in result.errors
    )
    result.promotion_blockers = sorted(set(result.promotion_blockers))
    result.promotion_eligible = (
        result.valid_schema
        and result.geometry_valid
        and result.provenance_valid
        and not result.promotion_blockers
        and stable_training_label
    )
    return result


def _check_enum_value(
    record: Dict[str, Any],
    field_name: str,
    allowed: set[str],
    result: CandidateVerification,
) -> None:
    value = record.get(field_name)
    if value not in allowed:
        result.valid_schema = False
        result.provenance_valid = False
        result.errors.append(f"invalid {field_name}: {value}")


def _check_bbox(bbox: Any, result: CandidateVerification) -> None:
    if bbox is None:
        return
    if not _is_number_list(bbox, 4):
        result.errors.append("invalid bbox: expected [x1, y1, x2, y2]")
        return
    if not (bbox[0] < bbox[2] and bbox[1] < bbox[3]):
        result.errors.append("invalid bbox: x1/y1 must be smaller than x2/y2")


def _check_point(point: Any, field_name: str, result: CandidateVerification) -> None:
    if point is None:
        return
    if not _is_number_list(point, 2):
        result.errors.append(f"invalid point {field_name}: expected [x, y]")


def _check_vector(vector: Any, field_name: str, result: CandidateVerification) -> None:
    if vector is None:
        return
    if not _is_number_list(vector, 2):
        result.errors.append(f"invalid vector {field_name}: expected [dx, dy]")
        return
    if vector[0] == 0 and vector[1] == 0:
        result.errors.append(f"invalid vector {field_name}: zero vector")


def _check_unit_vector(vector: Any, field_name: str, result: CandidateVerification) -> None:
    if vector is None or not _is_number_list(vector, 2):
        return
    norm = math.hypot(vector[0], vector[1])
    if norm == 0:
        return
    if not (0.98 <= norm <= 1.02):
        result.errors.append(f"invalid vector {field_name}: not unit length")


def _check_region(region: Any, field_name: str, result: CandidateVerification) -> None:
    if region is None:
        return
    if not isinstance(region, dict):
        result.errors.append(f"invalid region {field_name}: expected object")
        return
    points = region.get("points")
    if region.get("type") != "polygon" or not isinstance(points, list) or len(points) < 3:
        result.errors.append(f"invalid region {field_name}: expected polygon with >=3 points")
        return
    for idx, point in enumerate(points):
        if not _is_number_list(point, 2):
            result.errors.append(f"invalid region {field_name}: point {idx} must be [x, y]")


def _check_point_inside_bbox(
    point: Any,
    bbox: Any,
    field_name: str,
    result: CandidateVerification,
) -> None:
    if point is None or bbox is None:
        return
    if not (_is_number_list(point, 2) and _is_number_list(bbox, 4)):
        return
    if not (bbox[0] <= point[0] <= bbox[2] and bbox[1] <= point[1] <= bbox[3]):
        result.errors.append(f"{field_name} outside bbox")


def _check_point_inside_bbox_or_margin(
    point: Any,
    bbox: Any,
    field_name: str,
    result: CandidateVerification,
) -> None:
    if point is None or bbox is None:
        return
    if not (_is_number_list(point, 2) and _is_number_list(bbox, 4)):
        return
    width = bbox[2] - bbox[0]
    height = bbox[3] - bbox[1]
    margin = max(2.0, 0.05 * max(width, height))
    if not (
        bbox[0] - margin <= point[0] <= bbox[2] + margin
        and bbox[1] - margin <= point[1] <= bbox[3] + margin
    ):
        result.errors.append(f"{field_name} outside bbox margin")


def _check_point_inside_image(
    point: Any,
    record: Dict[str, Any],
    field_name: str,
    result: CandidateVerification,
) -> None:
    if point is None or not _is_number_list(point, 2):
        return
    width = record.get("image_width")
    height = record.get("image_height")
    if not (isinstance(width, (int, float)) and isinstance(height, (int, float))):
        return
    if not (0 <= point[0] <= width and 0 <= point[1] <= height):
        result.errors.append(f"{field_name} outside image")


def _check_region_inside_image(
    region: Any,
    record: Dict[str, Any],
    field_name: str,
    result: CandidateVerification,
) -> None:
    if not isinstance(region, dict):
        return
    width = record.get("image_width")
    height = record.get("image_height")
    if not (isinstance(width, (int, float)) and isinstance(height, (int, float))):
        return
    for point in region.get("points", []):
        if _is_number_list(point, 2) and not (0 <= point[0] <= width and 0 <= point[1] <= height):
            result.errors.append(f"{field_name} outside image")
            return


def _promotion_blockers(risk_flags: Sequence[str]) -> List[str]:
    blockers: List[str] = []
    for flag in risk_flags:
        if flag.startswith(PROMOTION_BLOCKING_RISK_PREFIXES):
            blockers.append(f"risk_{flag}")
    return blockers


def _is_number_list(value: Any, length: int) -> bool:
    if not isinstance(value, (list, tuple)) or len(value) != length:
        return False
    return all(isinstance(item, (int, float)) and not isinstance(item, bool) for item in value)
